// Fallback helper cho các ngôn ngữ khác (fr, de, es, ru, pt)
export const getMarketplaceText = (lang, key, params = {}) => {
  const dict = MP_TRANSLATIONS[lang] || MP_TRANSLATIONS.en;
  let text = dict[key] || MP_TRANSLATIONS.en[key] || MP_TRANSLATIONS.vi[key] || key;
  if (params && typeof text === 'string') {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
};
